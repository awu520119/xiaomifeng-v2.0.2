import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const temp = await mkdtemp(join(tmpdir(), 'coupon-flow-'));
try {
  for (const name of ['coupons', 'couponFlow']) {
    const source = await readFile(new URL(`../src/mock/${name}.ts`, import.meta.url), 'utf8');
    const output = stripTypeScriptTypes(source, { mode: 'strip' }).replaceAll("'./coupons'", "'./coupons.mjs'");
    await writeFile(join(temp, `${name}.mjs`), output);
  }
  const data = await import(pathToFileURL(join(temp, 'coupons.mjs')));
  const flow = await import(pathToFileURL(join(temp, 'couponFlow.mjs')));
  const experience = { ...data.initialCouponTemplates[0], id: 'TEST-EXP', totalLimit: 3, perUserLimit: 1 };
  const base = { version: 3, templates: [experience], tickets: [], plans: [], orders: [], accountRights: [] };
  const unauthorizedCoupon = { ...experience, id: 'TEST-UNAUTHORIZED', authorizedIssuerIds: ['issuer-wanglin'] };
  const unauthorizedStore = flow.prepareExperienceCodes({ ...base, templates: [unauthorizedCoupon] });
  assert.throws(() => flow.issueDirected(unauthorizedStore, unauthorizedCoupon.id, '13800000001'), /未获得.*发放权限/);
  assert.throws(() => flow.redeemExperience(unauthorizedStore, unauthorizedStore.tickets[0].redeemCode, '13800000001'), /未获得.*发放权限/);
  let store = flow.prepareExperienceCodes(base);
  assert.equal(store.tickets.length, 3); assert.equal(data.remainingQuota(experience, store.tickets), 3);
  assert.deepEqual(flow.prepareExperienceCodes(store).tickets.map((ticket) => ticket.id), store.tickets.map((ticket) => ticket.id));
  assert.ok(store.tickets.every((ticket) => ticket.serialNo));
  const targetCode = store.tickets[1];
  const boundToTarget = flow.issueDirected(store, experience.id, '13800000009', targetCode.id);
  assert.equal(boundToTarget.tickets.find((ticket) => ticket.id === targetCode.id).phoneDigits, '13800000009');
  assert.equal(boundToTarget.tickets.find((ticket) => ticket.id === store.tickets[0].id).phoneDigits, undefined);
  assert.throws(() => flow.issueDirected(store, experience.id, '13800000009,13800000010', targetCode.id), /仅可填写一个/);
  assert.throws(() => flow.issueDirected(store, experience.id, '13800000001,13800000002,13800000003,13800000004'), /不足/);
  const originalCodes = store.tickets.map((ticket) => ticket.redeemCode);
  store = flow.issueDirected(store, experience.id, '13800000001');
  assert.equal(store.tickets.length, 3); assert.notDeepEqual(store.tickets.map((ticket) => ticket.redeemCode), originalCodes);
  assert.match(store.tickets.find((ticket) => ticket.phoneDigits).redeemCode, /^CURRENT-ADMIN::/);
  assert.equal(data.remainingQuota(experience, store.tickets), 2);
  const duplicates = flow.issueDirected(flow.prepareExperienceCodes(base), experience.id, '13800000001,13800000001');
  assert.equal(duplicates.tickets.filter((ticket) => ticket.phoneDigits === '13800000001').length, 2);
  assert.equal(new Set(duplicates.tickets.map((ticket) => ticket.redeemCode)).size, 3);
  assert.equal(store.accountRights.some((right) => right.sourceTicketId === store.tickets.find((ticket) => ticket.phoneDigits).id), true);
  const assigned = store.tickets.find((ticket) => ticket.phoneDigits);
  const qr = `https://example.test/#/coupon-receive?code=${encodeURIComponent(assigned.redeemCode)}`;
  assert.equal(flow.resolveCouponCode(qr), assigned.redeemCode);
  assert.throws(() => flow.resolveCouponCode('https://example.test/#/coupon-receive?planId=CL-1'), /公开领取/);
  const right = store.accountRights.find((item) => item.sourceTicketId === assigned.id);
  assert.equal(right.expiresAt, assigned.expiresAt); assert.equal(right.phoneDigits, assigned.phoneDigits);
  assert.equal(flow.codeTracking(store.tickets.find((ticket) => ticket.id === assigned.id), store), '权益已到账');
  assert.throws(() => flow.redeemExperience(store, qr), /重复/);
  const unbound = store.tickets.find((ticket) => !ticket.phoneDigits);
  assert.throws(() => flow.redeemExperience(store, unbound.redeemCode), /手机号/);
  store = flow.redeemExperience(store, unbound.redeemCode, '13800000002', 'ACTIVITY-ORDER-001');
  assert.equal(store.accountRights[0].orderNo, 'ACTIVITY-ORDER-001');
  assert.equal(store.tickets.find((ticket) => ticket.id === unbound.id).orderNo, 'ACTIVITY-ORDER-001');
  assert.equal(store.tickets.filter((ticket) => ticket.phoneDigits).length, 2);
  assert.equal(flow.rightStatus({ ...right, expiresAt: data.dateTimeOffset(-1) }), '已过期');
  assert.throws(() => flow.createCouponOrder({ ...store, accountRights: [{ ...right, expiresAt: data.dateTimeOffset(-1) }] }, right.phoneDigits, right.productIds[0], right.id), /失效/);
  let rightsOrder = flow.createCouponOrder(store, right.phoneDigits, right.productIds[0], right.id);
  assert.equal(rightsOrder.orders[0].status, '待使用');
  assert.equal(rightsOrder.accountRights.find((item) => item.id === right.id).usageHistory?.length || 0, 0);
  assert.throws(() => flow.transitionOrder({ ...rightsOrder, accountRights: rightsOrder.accountRights.map((item) => ({ ...item, expiresAt: data.dateTimeOffset(-1) })) }, rightsOrder.orders[0].id, 'fulfil'), /有效期/);
  rightsOrder = flow.transitionOrder(rightsOrder, rightsOrder.orders[0].id, 'fulfil');
  assert.equal(rightsOrder.accountRights.find((item) => item.id === right.id).usageHistory.length, 1);
  const claimBase = flow.prepareExperienceCodes({ ...base, plans: [{ id: 'PLAN-EXP', couponId: experience.id, allowedPhones: [], createdAt: data.couponLocalTime() }] });
  const byLink = flow.claimPublicCoupon(claimBase, 'PLAN-EXP', '13800000006');
  assert.equal(byLink.store.accountRights.find((item) => item.sourceTicketId === byLink.ticketId)?.phoneDigits, '13800000006');
  assert.doesNotThrow(() => flow.createCouponOrder(byLink.store, '13800000006', experience.productIds[0], byLink.store.accountRights.find((item) => item.sourceTicketId === byLink.ticketId).id));
  const byCode = flow.claimExperienceCode(claimBase, claimBase.tickets[0].redeemCode, '13800000007');
  assert.equal(byCode.store.accountRights.find((item) => item.sourceTicketId === byCode.ticketId)?.phoneDigits, '13800000007');
  assert.equal(flow.claimExperienceCode(byCode.store, claimBase.tickets[0].redeemCode, '13800000007').alreadyClaimed, true);
  assert.throws(() => flow.claimExperienceCode(byCode.store, claimBase.tickets[0].redeemCode, '13800000008'), /已被领取/);
  const presented = flow.markExperienceCodeDistributed(claimBase, claimBase.tickets[1].id, data.currentCouponOperatorId);
  assert.equal(presented.tickets[1].distributedById, data.currentCouponOperatorId);
  assert.equal(presented.tickets[1].phoneDigits, undefined);
  assert.equal(flow.markExperienceCodeDistributed(presented, presented.tickets[1].id, data.currentCouponOperatorId), presented);
  assert.throws(() => flow.markExperienceCodeDistributed(presented, presented.tickets[1].id, 'issuer-wanglin'), /权限/);
  const claimedPresented = flow.claimExperienceCode(presented, presented.tickets[1].redeemCode, '13800000011').store;
  assert.equal(claimedPresented.tickets[1].distributedById, data.currentCouponOperatorId);
  assert.equal(claimedPresented.tickets[1].phoneDigits, '13800000011');
  assert.notEqual(flow.claimPublicCoupon(presented, 'PLAN-EXP', '13800000012').ticketId, presented.tickets[1].id);
  console.log('✓ 发券授权、自动备码、编号精确绑定、额度、重复手机号逐条发券、扫码链接、指定账户与订单关联、核销防重、权益有效期及履约统计');

  const price = { ...data.initialCouponTemplates[2], id: 'TEST-PRICE', kind: '满减券', minSpend: 20, discountAmount: 10 };
  const ticket = data.createTicket(price, '定向发放', '13800000008');
  const priceStore = { ...base, templates: [price], tickets: [ticket] };
  let pending = flow.createCouponOrder(priceStore, ticket.phoneDigits, 'SP001', ticket.id);
  const orderId = pending.orders[0].id;
  assert.throws(() => flow.createCouponOrder(pending, ticket.phoneDigits, 'SP001', ticket.id), /占用/);
  const cancelled = flow.transitionOrder(pending, orderId, 'cancel');
  assert.equal(cancelled.tickets[0].lockedOrderId, undefined);
  const paid = flow.transitionOrder(pending, orderId, 'pay');
  assert.equal(paid.orders[0].status, '待使用'); assert.equal(paid.tickets[0].usedTimes, 1);
  const returned = flow.transitionOrder(paid, orderId, 'refund-full');
  assert.equal(returned.tickets[0].usedTimes, 0); assert.ok(returned.tickets[0].usageHistory[0].couponReturnedAt);
  assert.match(returned.orders[0].couponReturnResult, /已返还/);
  assert.throws(() => flow.transitionOrder(returned, orderId, 'refund-full'), /不能退款/);
  assert.doesNotThrow(() => flow.createCouponOrder(returned, ticket.phoneDigits, 'SP001', ticket.id));
  const partial = flow.transitionOrder(paid, orderId, 'refund-partial');
  assert.equal(partial.tickets[0].usedTimes, 1); assert.match(partial.orders[0].couponReturnResult, /部分退款/);
  const partialFulfilled = flow.transitionOrder(partial, orderId, 'fulfil');
  assert.equal(partialFulfilled.orders[0].status, '已完成');
  assert.throws(() => flow.transitionOrder(partialFulfilled, orderId, 'refund-full'), /不能退款/);
  const fulfilled = flow.transitionOrder(paid, orderId, 'fulfil');
  const fulfilledRefund = flow.transitionOrder(fulfilled, orderId, 'refund-full');
  assert.equal(fulfilledRefund.tickets[0].usedTimes, 1); assert.match(fulfilledRefund.orders[0].couponReturnResult, /已履约/);
  const expiredRefund = flow.transitionOrder({ ...paid, tickets: [{ ...paid.tickets[0], expiresAt: data.dateTimeOffset(-1) }] }, orderId, 'refund-full');
  assert.equal(expiredRefund.tickets[0].usedTimes, 1); assert.match(expiredRefund.orders[0].couponReturnResult, /失效/);
  const zero = { ...ticket, discountAmount: 100 };
  assert.match(flow.priceCouponReason(zero, 'SP001'), /应付为 0/);
  assert.throws(() => flow.createCouponOrder({ ...priceStore, tickets: [zero] }, ticket.phoneDigits, 'SP001', ticket.id), /应付为 0/);
  console.log('✓ 价格券零元拦截、下单锁券、关闭释放、全额退款返券、部分退款/履约/过期不返券及历史保留');
} finally { await rm(temp, { recursive: true, force: true }); }
